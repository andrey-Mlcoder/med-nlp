def get_severity_weight(code, class_weights, block_weights, rubric_overrides):
    # 1. Точное совпадение рубрики
    if code in rubric_overrides:
        return rubric_overrides[code]
    # 2. Поиск по блоку (первые 3 символа)
    block = code[:3]
    if block in block_weights:
        return block_weights[block]
    # 3. По классу (первая буква)
    letter = code[0]
    if letter in class_weights:
        return class_weights[letter]
    # 4. Fallback
    return 0.5

